// Visual check of the M2 features. Usage: node e2e/probe-m2.mjs <raw-asset-id> <out-dir>
import { join } from 'node:path';
import { chromium } from 'playwright-core';
const BASE = 'http://127.0.0.1:8088';
const [id, out] = process.argv.slice(2);
const browser = await chromium.launch({ channel: 'msedge', headless: true, args: ['--enable-gpu', '--use-angle=d3d11'] });
const ctx = await browser.newContext({ viewport: { width: 1600, height: 950 } });
await ctx.request.post(`${BASE}/api/auth/login`, { data: { email: 'admin@example.com', password: 'raw-editor-e2e' } });
const page = await ctx.newPage();
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
page.on('console', (m) => m.type() === 'error' && errors.push(m.text()));
await page.goto(`${BASE}/immich-raw/?asset=${id}&debug`);
await page.locator('.frame:not(.hidden) canvas').waitFor({ timeout: 120000 });
await page.waitForTimeout(700);
await page.screenshot({ path: join(out, 'm2-1-layout.png') });
for (const [label, v] of [['Clarity', '60'], ['Texture', '50'], ['Dehaze', '40']]) await page.locator(`input[aria-label="${label}"]`).fill(v);
await page.waitForTimeout(600);
await page.screenshot({ path: join(out, 'm2-2-presence.png') });
await page.getByRole('button', { name: 'Tone Curve' }).click();
await page.getByRole('button', { name: 'RGB' }).click();
await page.evaluate(() => { const ed = globalThis.__editor; ed.setCurvePoints('master', [[0, 0], [64, 44], [192, 214], [255, 255]], true); });
await page.waitForTimeout(600);
await page.screenshot({ path: join(out, 'm2-3-curve.png') });
await page.evaluate(() => globalThis.__editor.setMaskView('highlights'));
await page.waitForTimeout(400);
await page.screenshot({ path: join(out, 'm2-4-alt-highlights.png') });
await page.evaluate(() => globalThis.__editor.setMaskView('none'));
// wait for full decode, then double-click the canvas
await page.waitForFunction(() => globalThis.__editor.fullStatus === 'ready', null, { timeout: 120000 });
const box = await page.locator('.frame canvas').boundingBox();
await page.mouse.dblclick(box.x + box.width * 0.42, box.y + box.height * 0.3);
await page.waitForTimeout(900);
const z = await page.evaluate(() => ({ ...globalThis.__editor.zoom }));
await page.screenshot({ path: join(out, 'm2-5-zoom.png') });
await page.mouse.move(800, 450); await page.mouse.down(); await page.mouse.move(500, 300, { steps: 8 }); await page.mouse.up();
await page.waitForTimeout(600);
const z2 = await page.evaluate(() => ({ ...globalThis.__editor.zoom }));
await page.screenshot({ path: join(out, 'm2-6-panned.png') });
const hist = await page.evaluate(() => globalThis.__editor.historySteps.map((s) => s.label));
console.log(JSON.stringify({ zoom: z, afterPan: z2, history: hist, errors }, null, 1));
await browser.close();
